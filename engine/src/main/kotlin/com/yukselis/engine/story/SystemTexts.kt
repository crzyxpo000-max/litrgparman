 * Motorun ürettiği Sistem bildirimlerinin kalıp metinleri (content/system.json).
 * Yer tutucular adlandırılmıştır: "+{n} XP", "Seviye {from} → {to}".
 * Yer tutucu değerleri iki dilde ayrı verilebilir (unvan adı gibi).
